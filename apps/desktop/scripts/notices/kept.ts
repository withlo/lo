/** An entry with the text of its license file, when it has one. */
export interface KeptNotice extends Kept {
  readonly licenseText?: string;
}

/** The entries, each with the text of its `licenseFile` read from the repository at `root`. */
export function keptNotices(root: string): KeptNotice[] {
  return KEPT.map((entry) =>
    entry.licenseFile === undefined
      ? entry
      : { ...entry, licenseText: readFileSync(join(root, entry.licenseFile), 'utf8').trim() },
  );
}
