// What Lo ships that isn't an npm package, and so isn't in what the build bundles: the code and data
// copied into the repository, and what a build step puts in the output. Each entry names where it
// comes from, at which commit, what Lo has of it, and the license and copyright that go with it.
// `kept.test.ts` checks the list against the files themselves: every grammar `grammars.json` pins
// and every file under `syntax/queries` that says where it was copied from has an entry at that
// commit and under that license. Add an entry in the same change that adds the files.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/** The licenses the kept entries are under. */
export type KeptLicense = 'MIT' | 'Apache-2.0' | 'GPL-3.0-or-later';

export interface Kept {
  /** The GitHub repository it comes from, `owner/name`. */
  readonly repo: string;
  /** The commit or release of that repository the copy is of, when it's a copy of one. */
  readonly at?: string;
  /** What Lo has of it. */
  readonly provides: string;
  readonly license: KeptLicense;
  /** The copyright lines its license, or the files' own headers, give. */
  readonly copyright: readonly string[];
  /** Its NOTICE file, which the Apache License asks to be kept with the work. */
  readonly notice?: string;
  /** A file in this repository, from the repository's root, that holds its license in full. */
  readonly licenseFile?: string;
}

const mit = (
  repo: string,
  at: string | undefined,
  provides: string,
  ...copyright: string[]
): Kept => ({ repo, ...(at === undefined ? {} : { at }), provides, license: 'MIT', copyright });

const apache = (
  repo: string,
  at: string | undefined,
  provides: string,
  ...copyright: string[]
): Kept => ({
  repo,
  ...(at === undefined ? {} : { at }),
  provides,
  license: 'Apache-2.0',
  copyright,
});

